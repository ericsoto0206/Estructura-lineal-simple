# Solicitar información al usuario
nombre = input("Ingresa tu nombre: ")
edad = input("Ingresa tu edad: ")
ciudad = input("Ingresa tu ciudad de residencia: ")

# Información adicional para la historia
profesion = input("¿Cuál es tu profesión o a qué te dedicas?: ")
hobby = input("¿Cuál es tu pasatiempo favorito?: ")
sueno = input("¿Cuál es tu mayor sueño?: ")
comida = input("¿Cuál es tu comida favorita?: ")
color = input("¿Cuál es tu color favorito?: ")
pais = input("¿Qué país te gustaría visitar?: ")

# Crear la historia
print(f"\n=== LA HISTORIA DE {nombre.upper()} ===\n")
print(f"{nombre} tiene {edad} años y vive en {ciudad}.")
print(f"Se dedica a {profesion} y en su tiempo libre disfruta {hobby}.")
print(f"A pesar de su rutina diaria, {nombre} nunca olvida que su mayor sueño es {sueno}.")
print(f"Un día, mientras caminaba por las calles de {ciudad}, {nombre} decidió que era el momento de perseguir ese sueño...")
print(f"Antes de comenzar su aventura, disfrutó de su comida favorita: {comida}.")
print(f"Vestía ropa de color {color}, lo que le daba mucha confianza.")
print(f"Además, deseaba conocer {pais} y aprender sobre su cultura.")
print(f"Con esfuerzo y dedicación, {nombre} sabía que podía alcanzar sus metas.")
print(f"Desde entonces, cada día trabajó para acercarse a su sueño de {sueno}.")
print(f"Y así comenzó una nueva etapa llena de retos, aprendizaje y grandes oportunidades.")
print(f"Con cada paso que daba, {nombre} ganaba experiencia y confianza en sí mismo.")
print(f"Su historia demuestra que la perseverancia es la clave para alcanzar cualquier meta.")
